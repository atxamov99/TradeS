export type AuthText = typeof uz;
export const authTexts = { uz, ru, en };

/** Auth-screen texts in the language chosen in the app (same language switch as the website). */
export function useAuthText(): AuthText {
  const lang = useLangStore((s) => s.lang);
  return authTexts[lang] ?? uz;
}
